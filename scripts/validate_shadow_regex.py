"""Native PCRE2 scope tests for the v2 trial; not an in-game validation."""
import argparse
import ctypes as c
from pathlib import Path
import re


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--pcre2', required=True)
    parser.add_argument('--shader', required=True)
    parser.add_argument('--output', required=True)
    args = parser.parse_args()
    ini = Path(__file__).resolve().parents[1].joinpath('d3dx.ini').read_text(encoding='utf8')

    def section(name):
        return ini.split('[' + name + ']\n', 1)[1].split('\n\n', 1)[0].strip()

    shader = Path(args.shader).read_text(encoding='utf-8-sig')
    asm = shader[re.search(r'^vs_5_0\s*$', shader, re.M).start():]
    pattern = section('ShaderRegexYYSLSShadowMarker.Pattern').encode()
    replacement = section('ShaderRegexYYSLSShadowMarker.Pattern.Replace')
    scratch_index = int(re.search(r'^dcl_temps (\d+)', asm, re.M)[1])
    replacement = replacement.replace('${shadowMarker}', f'r{scratch_index}').encode()
    dll = c.CDLL(str(Path(args.pcre2).resolve()))
    compile_ = dll.pcre2_compile_8
    compile_.argtypes = [c.c_char_p, c.c_size_t, c.c_uint32,
                         c.POINTER(c.c_int), c.POINTER(c.c_size_t), c.c_void_p]
    compile_.restype = c.c_void_p
    error, offset = c.c_int(), c.c_size_t()
    code = compile_(pattern, len(pattern), 0x408, c.byref(error), c.byref(offset), None)
    assert code, (error.value, offset.value)
    sub = dll.pcre2_substitute_8
    sub.argtypes = [c.c_void_p, c.c_char_p, c.c_size_t, c.c_size_t,
                   c.c_uint32, c.c_void_p, c.c_void_p, c.c_char_p,
                   c.c_size_t, c.c_void_p, c.POINTER(c.c_size_t)]
    sub.restype = c.c_int
    free = dll.pcre2_code_free_8
    free.argtypes = [c.c_void_p]

    def patch(subject):
        data = subject.encode()
        output = c.create_string_buffer(len(data) + 8192)
        size = c.c_size_t(len(output))
        count = sub(code, data, len(data), 0, 0x1200, None, None,
                    replacement, len(replacement), output, c.byref(size))
        assert count >= 0, count
        return count, output.raw[:size.value].decode()

    try:
        count, patched = patch(asm)
        assert count == 1
        assert patched.count('ld_indexable') == asm.count('ld_indexable') + 1
        assert f'and r0.w, r0.w, r{scratch_index}.x\nif_nz r0.w' in patched
        # The actual disassembler includes reflection/signature comments.
        header = '// Generated by Microsoft HLSL Shader Compiler\n//\n\n'
        n, with_header = patch(header + asm)
        assert n == 1 and with_header == header + patched
        # Fail closed when the layout, resource type, vertex-ID path, output
        # signature or reserved slot differs from the observed shadow family.
        mutations = [
            asm.replace('CB0[75]', 'CB0[76]'),
            asm.replace('CB3[768]', 'CB3[769]'),
            asm.replace('texture2darray', 'texture2d'),
            asm.replace('vertex_id', 'instance_id'),
            asm.replace('dcl_temps ', 'dcl_output o3.xyzw\ndcl_temps '),
            asm.replace('dcl_temps ', 'dcl_resource_buffer (float,float,float,float) t119\ndcl_temps '),
            asm.replace('cb0[74].x', 'cb0[73].x'),
            asm.replace('t11.xyzw', 't10.xyzw'),
        ]
        for subject in mutations:
            n, result = patch(subject)
            assert n == 0 and result == subject
        patched = patched.replace(f'dcl_temps {scratch_index}', f'dcl_temps {scratch_index + 1}', 1)
        patched = patched.replace('dcl_temps ', section('ShaderRegexYYSLSShadowMarker.InsertDeclarations') + '\ndcl_temps ', 1)
        Path(args.output).write_text(patched, encoding='utf8')
        print('PASS: native PCRE2 replacement, eight incompatible shader rejections, register/declaration expansion')
        print('Full DXBC assembly and in-game execution still require validation.')
    finally:
        free(code)


if __name__ == '__main__':
    main()
